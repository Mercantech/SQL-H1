CREATE TABLE tournament (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(100) NOT NULL,
    game_title varchar(80) NOT NULL,
    max_players integer NOT NULL CHECK (max_players > 0),
    starts_at_utc timestamptz NOT NULL
);

CREATE TABLE registration (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id integer NOT NULL REFERENCES tournament(id) ON DELETE RESTRICT,
    player_tag varchar(40) NOT NULL,
    joined_at_utc timestamptz NOT NULL,
    CONSTRAINT uq_registration_player UNIQUE (tournament_id, player_tag)
);

CREATE INDEX ix_registration_tournament ON registration(tournament_id);

